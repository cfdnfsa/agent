-- 模型配置、流程配置与提示词配置建表脚本，适用于 PostgreSQL 14+，在目标数据库中执行。
-- 仅创建尚不存在的表；已有表的字段变更需另写迁移脚本。

-- 模型表
CREATE TABLE IF NOT EXISTS model_config
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_name     VARCHAR(100)  NOT NULL,
    model_code     VARCHAR(255)  NOT NULL,
    model_provider VARCHAR(32)   NOT NULL,
    model_base_url VARCHAR(1024) NOT NULL,
    model_api_key  TEXT          NULL
);

COMMENT ON TABLE model_config IS '模型配置';
COMMENT ON COLUMN model_config.id IS '模型配置ID';
COMMENT ON COLUMN model_config.model_name IS '模型显示名称';
COMMENT ON COLUMN model_config.model_code IS '调用服务时使用的模型标识';
COMMENT ON COLUMN model_config.model_provider IS '接入方式：openai=OpenAI兼容，ollama=Ollama，anthropic=Anthropic，google_genai=Gemini';
COMMENT ON COLUMN model_config.model_base_url IS '模型服务Base URL';
COMMENT ON COLUMN model_config.model_api_key IS 'API Key；当前明文保存；无需密钥时为空；查询接口不返回';

-- 流程定义按文本原样保存，不使用 JSON/JSONB 类型。
CREATE TABLE IF NOT EXISTS workflow_config
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_name       VARCHAR(100) NOT NULL,
    workflow_definition TEXT         NOT NULL
);

COMMENT ON TABLE workflow_config IS '流程配置';
COMMENT ON COLUMN workflow_config.id IS '流程配置ID';
COMMENT ON COLUMN workflow_config.workflow_name IS '流程名称';
COMMENT ON COLUMN workflow_config.workflow_definition IS '流程定义文本；保存JSON字符串，当前不解析或校验';

-- 多个流程节点可复用同一份提示词，节点引用后续保存在流程定义中。
CREATE TABLE IF NOT EXISTS prompt_config
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prompt_name    VARCHAR(100) NOT NULL,
    prompt_content TEXT         NOT NULL
);

COMMENT ON TABLE prompt_config IS '提示词配置';
COMMENT ON COLUMN prompt_config.id IS '提示词配置ID';
COMMENT ON COLUMN prompt_config.prompt_name IS '提示词名称';
COMMENT ON COLUMN prompt_config.prompt_content IS '提示词正文';
